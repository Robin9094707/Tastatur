// MARK: - Frisch Kopiertes oben in der Leiste (wie bei iOS 26)

struct ClipPeek: Equatable {
    enum Kind: Equatable { case text, link, image, file, secret }
    var kind: Kind
    /// Kurze Vorschau (nie das ganze Passwort).
    var preview: String
    var changeCount: Int
    var thumbnail: UIImage?

    static func == (a: ClipPeek, b: ClipPeek) -> Bool {
        a.kind == b.kind && a.preview == b.preview && a.changeCount == b.changeCount && (a.thumbnail == nil) == (b.thumbnail == nil)
    }

    var icon: String {
        switch kind {
        case .text: return "doc.on.clipboard"
        case .link: return "link"
        case .image: return "photo"
        case .file: return "doc.fill"
        case .secret: return "key.fill"
        }
    }

    /// Bilder/Dateien kann eine Tastatur nicht selbst einsetzen (iOS-Grenze).
    var insertable: Bool { kind == .text || kind == .link || kind == .secret }

    /// Typen, mit denen Passwort-Apps „geheime“ Kopien markieren – nie im Verlauf speichern.
    static let concealedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "com.apple.is-sensitive",
    ]
    static func isConcealed(_ types: [String]) -> Bool { types.contains { concealedTypes.contains($0) } }

    static let imageTypes = ["public.heic", "public.jpeg", "public.png", "com.compuserve.gif", "public.tiff", "public.webp", "org.webmproject.webp"]

    /// Wie lange Kopiertes oben angeboten wird.
    static let freshness: TimeInterval = 5 * 60

    /// Kleines Vorschaubild – nie das ganze Bild dekodieren (Speicherlimit!).
    static func thumbnail(from data: Data, maxPixel: Int = 96) -> UIImage? {
        guard let src = CGImageSourceCreateWithData(data as CFData, [kCGImageSourceShouldCache: false] as CFDictionary) else { return nil }
        let opts: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceThumbnailMaxPixelSize: maxPixel,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceShouldCacheImmediately: true,
        ]
        guard let cg = CGImageSourceCreateThumbnailAtIndex(src, 0, opts as CFDictionary) else { return nil }
        return UIImage(cgImage: cg)
    }
}

// MARK: - Passwort-Apps

struct PasswordApp: Identifiable, Equatable {
    var id: String
    var name: String
    var url: String
}

enum PasswordApps {
    static let all: [PasswordApp] = [
        PasswordApp(id: "apple", name: "Passwörter", url: "prefs:root=PASSWORDS"),
        PasswordApp(id: "1password", name: "1Password", url: "onepassword://"),
        PasswordApp(id: "bitwarden", name: "Bitwarden", url: "bitwarden://"),
        PasswordApp(id: "proton", name: "Proton Pass", url: "proton-pass://"),
        PasswordApp(id: "dashlane", name: "Dashlane", url: "dashlane://"),
        PasswordApp(id: "keeper", name: "Keeper", url: "keeper://"),
        PasswordApp(id: "lastpass", name: "LastPass", url: "lastpass://"),
        PasswordApp(id: "nordpass", name: "NordPass", url: "nordpass://"),
        PasswordApp(id: "enpass", name: "Enpass", url: "enpass://"),
        PasswordApp(id: "strongbox", name: "Strongbox", url: "strongbox://"),
        PasswordApp(id: "keepassium", name: "KeePassium", url: "keepassium://"),
    ]

    static func current(_ store: SharedStore) -> PasswordApp? {
        switch store.passwordApp {
        case "auto", "": return nil
        case "custom":
            let u = store.passwordAppURL.trimmingCharacters(in: .whitespaces)
            guard !u.isEmpty else { return nil }
            let scheme = u.components(separatedBy: ":").first ?? u
            return PasswordApp(id: "custom", name: scheme.capitalized, url: u.contains(":") ? u : u + "://")
        default: return all.first { $0.id == store.passwordApp }
        }
    }
}

// MARK: - Logik

extension KeyboardState {

    // MARK: Zwischenablage-Vorschau

    /// Wird bei jeder Änderung der Zwischenablage aufgerufen (Timer, schon gedrosselt).
    func updateClipPeek(_ pb: UIPasteboard, types: [String], secret: Bool) {
        guard store.clipPeek, hasFullAccess else { if bar.clip != nil { bar.clip = nil }; return }
        let count = pb.changeCount
        let d = store.defaults
        if d.integer(forKey: "peek.count") != count {
            d.set(count, forKey: "peek.count")
            d.set(Date().timeIntervalSince1970, forKey: "peek.seen")
        }
        let seen = Date(timeIntervalSince1970: d.double(forKey: "peek.seen"))
        guard d.integer(forKey: "peek.done") != count, Date().timeIntervalSince(seen) < ClipPeek.freshness else {
            if bar.clip != nil { bar.clip = nil }
            return
        }
        guard let peek = makePeek(pb, types: types, secret: secret, count: count) else {
            if bar.clip != nil { bar.clip = nil }
            return
        }
        if bar.clip != peek {
            bar.clip = peek
            if bar.clipHidden { bar.clipHidden = false }
        }
        if peek.kind == .image { loadPeekThumbnail(pb, types: types, count: count) }
    }

    func makePeek(_ pb: UIPasteboard, types: [String], secret: Bool, count: Int) -> ClipPeek? {
        if secret {
            return ClipPeek(kind: .secret, preview: "Passwort · ••••••••", changeCount: count)
        }
        if types.contains(where: { ClipPeek.imageTypes.contains($0) }) || pb.hasImages {
            return ClipPeek(kind: .image, preview: "Bild", changeCount: count, thumbnail: bar.clip?.changeCount == count ? bar.clip?.thumbnail : nil)
        }
        if pb.hasStrings, let s = pb.string {
            let t = s.trimmingCharacters(in: .whitespacesAndNewlines)
            guard !t.isEmpty else { return nil }
            if ChatGPTAuth.isTransferCode(t) { return nil }
            let isLink = !t.contains(" ") && !t.contains("\n") && (t.hasPrefix("http://") || t.hasPrefix("https://") || t.hasPrefix("www."))
            var preview = t.replacingOccurrences(of: "\n", with: " ")
            if isLink {
                preview = preview.replacingOccurrences(of: "https://", with: "").replacingOccurrences(of: "http://", with: "")
            }
            if preview.count > 60 { preview = String(preview.prefix(58)) + "…" }
            return ClipPeek(kind: isLink ? .link : .text, preview: preview, changeCount: count)
        }
        if pb.hasURLs, let url = pb.url {
            if url.isFileURL { return ClipPeek(kind: .file, preview: url.lastPathComponent, changeCount: count) }
            return ClipPeek(kind: .link, preview: url.absoluteString, changeCount: count)
        }
        // Sonstige Dateien (PDF, Dokumente …): Art anzeigen
        if let t = types.first(where: { !$0.hasPrefix("dyn.") && !ClipPeek.concealedTypes.contains($0) }) {
            let name = UTType(t)?.localizedDescription ?? "Datei"
            return ClipPeek(kind: .file, preview: name, changeCount: count)
        }
        return nil
    }

    private func loadPeekThumbnail(_ pb: UIPasteboard, types: [String], count: Int) {
        guard bar.clip?.thumbnail == nil else { return }
        var raw: Data?
        for t in ClipPeek.imageTypes where types.contains(t) {
            if let d = pb.data(forPasteboardType: t) { raw = d; break }
        }
        guard let data = raw, data.count < 40_000_000 else { return }
        DispatchQueue.global(qos: .userInitiated).async { [weak self] in
            let thumb = ClipPeek.thumbnail(from: data)
            DispatchQueue.main.async {
                guard let self, let thumb, var c = self.bar.clip, c.changeCount == count else { return }
                c.thumbnail = thumb
                self.bar.clip = c
            }
        }
    }

    /// Was gerade in der Zwischenablage liegt (für die Ablage – ohne Ablaufzeit).
    func currentClipPeek(thumbnail: @escaping (UIImage) -> Void) -> ClipPeek? {
        guard hasFullAccess else { return nil }
        let pb = UIPasteboard.general
        let types = pb.types
        guard let peek = makePeek(pb, types: types, secret: ClipPeek.isConcealed(types), count: pb.changeCount) else { return nil }
        if peek.kind == .image {
            var raw: Data?
            for t in ClipPeek.imageTypes where types.contains(t) {
                if let d = pb.data(forPasteboardType: t) { raw = d; break }
            }
            if let data = raw, data.count < 40_000_000 {
                DispatchQueue.global(qos: .userInitiated).async {
                    guard let img = ClipPeek.thumbnail(from: data, maxPixel: 160) else { return }
                    DispatchQueue.main.async { thumbnail(img) }
                }
            }
        }
        return peek
    }

    /// Tipp auf die Vorschau: Text/Link/Passwort direkt einsetzen.
    func pasteClipPeek() {
        guard let peek = bar.clip else { return }
        if paste(peek) { markPeekDone() }
    }

    /// Setzt Kopiertes ein. Bilder/Dateien: Hinweis, wie iOS sie einfügt.
    @discardableResult
    func paste(_ peek: ClipPeek) -> Bool {
        let pb = UIPasteboard.general
        guard peek.insertable else {
            feedback()
            if peek.kind == .image {
                showToast("Bilder fügt nur iOS ein: Textfeld gedrückt halten → „Einfügen“")
            } else {
                showToast("Dateien fügt nur iOS ein: Textfeld gedrückt halten → „Einfügen“")
            }
            return false
        }
        var text = pb.string ?? pb.url?.absoluteString ?? ""
        if peek.kind != .secret { text = text.trimmingCharacters(in: .newlines) }
        guard !text.isEmpty else { markPeekDone(); return false }
        feedback(.medium)
        if composeMode {
            composeText += text
        } else {
            if peek.kind != .secret, let last = before.last, last.isLetter || last.isNumber || ".,!?:;".contains(last) { text = " " + text }
            proxy?.insertText(text)
            afterCommit()
        }
        return true
    }

    /// Bild aus der Vorschau direkt als Sticker sichern.
    func peekToSticker() {
        addStickerFromClipboard()
        markPeekDone()
    }

    func dismissClipPeek() {
        feedback()
        markPeekDone()
    }

    func markPeekDone() {
        if let c = bar.clip { store.defaults.set(c.changeCount, forKey: "peek.done") }
        bar.clip = nil
    }

    /// Beim Tippen ausblenden (nicht verwerfen) – im leeren Feld kommt sie zurück.
    func hideClipPeekWhileTyping() {
        guard bar.clip != nil, !bar.clipHidden else { return }
        bar.clipHidden = true
    }

    /// Feld wieder leer → Vorschau zurückholen.
    func restoreClipPeekIfEmpty() {
        guard bar.clipHidden, let proxy, !proxy.hasText else { return }
        bar.clipHidden = false
    }

    // MARK: Passwörter / Anmeldefelder

    /// Erkennt Anmeldefelder (Benutzername, E-Mail, Passwort). Billig – läuft bei jeder Textänderung.
    func updateLoginField() {
        guard store.passwordHelper, !composeMode, let proxy else {
            if bar.login { bar.login = false }
            return
        }
        let ct: UITextContentType? = proxy.textContentType ?? nil
        var isLogin = false
        if let ct {
            isLogin = ct == .username || ct == .password || ct == .newPassword || ct == .oneTimeCode
            if ct == .emailAddress, proxy.keyboardType == .emailAddress { isLogin = true }
        }
        let show = isLogin && !proxy.hasText
        if bar.login != show { bar.login = show }
        if isLogin, store.loginAutoSwitch { autoSwitchForLogin(proxy) }
    }

    /// Einmal pro Feld automatisch zur iOS-Tastatur wechseln (dort zeigt iOS die Passwort-App).
    private func autoSwitchForLogin(_ proxy: UITextDocumentProxy) {
        let id = proxy.documentIdentifier.uuidString
        let d = store.defaults
        guard d.string(forKey: "login.autoSwitched") != id, !proxy.hasText else { return }
        d.set(id, forKey: "login.autoSwitched")
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.15) { [weak self] in
            self?.controller?.advanceToNextInputMode()
        }
    }

    /// „Passwörter“: zur iOS-Tastatur wechseln – dort erscheint der Schlüssel deiner Passwort-App (Autofill).
    func switchToAutofill() {
        feedback(.medium)
        controller?.advanceToNextInputMode()
    }

    /// Öffnet die gewählte Passwort-App. Kopierst du dort das Passwort, steht es hier oben zum Einsetzen bereit.
    func openPasswordApp() {
        guard let app = PasswordApps.current(store), let url = URL(string: app.url) else {
            switchToAutofill()
            return
        }
        feedback(.medium)
        controller?.openURL(url)
        showToast("Passwort in \(app.name) kopieren – es erscheint dann hier oben 🔑")
    }
}

// MARK: - Leisten-Ansichten

struct ClipPeekRow: View {
    @ObservedObject var state: KeyboardState
    let peek: ClipPeek
    var replies: Bool

    var body: some View {
        HStack(spacing: 6) {
            Button { state.pasteClipPeek() } label: {
                HStack(spacing: 8) {
                    thumb
                    VStack(alignment: .leading, spacing: 0) {
                        Text(peek.insertable ? "Einfügen" : (peek.kind == .image ? "Kopiertes Bild" : "Kopierte Datei"))
                            .font(.system(size: 10, weight: .semibold))
                            .foregroundStyle(.secondary)
                        Text(peek.preview)
                            .font(.system(size: 13, weight: .semibold))
                            .foregroundStyle(.primary)
                            .lineLimit(1)
                            .truncationMode(.tail)
                    }
                    Spacer(minLength: 0)
                }
                .padding(.leading, 4)
                .padding(.trailing, 10)
                .frame(maxWidth: .infinity, minHeight: 32)
                .background(Capsule().fill(state.tint.opacity(0.22)))
                .overlay(Capsule().strokeBorder(state.tint.opacity(0.35), lineWidth: 0.5))
                .contentShape(Capsule())
            }
            .buttonStyle(PressableStyle())
            if peek.kind == .image {
                smallButton("face.smiling.inverse") { state.peekToSticker() }
            }
            if replies {
                smallButton("bubble.left.and.text.bubble.right.fill") { state.suggestReplies(manual: false) }
            }
            Button { state.dismissClipPeek() } label: {
                Image(systemName: "xmark").font(.system(size: 12, weight: .semibold))
                    .foregroundStyle(.secondary)
                    .frame(width: 28, height: 32)
                    .contentShape(Rectangle())
            }
            .buttonStyle(.plain)
        }
        .padding(.horizontal, 3)
    }

    @ViewBuilder
    private var thumb: some View {
        if let img = peek.thumbnail {
            Image(uiImage: img)
                .resizable()
                .scaledToFill()
                .frame(width: 28, height: 28)
                .clipShape(RoundedRectangle(cornerRadius: 7, style: .continuous))
                .overlay(RoundedRectangle(cornerRadius: 7, style: .continuous).strokeBorder(.white.opacity(0.4), lineWidth: 0.5))
        } else {
            Image(systemName: peek.icon)
                .font(.system(size: 12, weight: .bold))
                .foregroundStyle(.white)
                .frame(width: 28, height: 28)
                .background(Circle().fill(state.tint.gradient))
        }
    }

    private func smallButton(_ symbol: String, action: @escaping () -> Void) -> some View {
        Button(action: action) {
            Image(systemName: symbol).font(.system(size: 13, weight: .semibold))
                .foregroundStyle(state.tint)
                .frame(width: 32, height: 32)
                .background(Circle().fill(state.tint.opacity(0.15)))
        }
        .buttonStyle(PressableStyle())
    }
}

