/// Weiches Eindrücken wie bei iOS – fühlt sich flüssiger an als der Standard-Stil.
struct PressableStyle: ButtonStyle {
    func makeBody(configuration: Configuration) -> some View {
        configuration.label
            .scaleEffect(configuration.isPressed ? 0.95 : 1)
            .opacity(configuration.isPressed ? 0.85 : 1)
            .animation(.spring(response: 0.22, dampingFraction: 0.7), value: configuration.isPressed)
    }
}

/// Oben in der Ablage: was gerade kopiert ist – mit Miniatur.
struct CurrentClipCard: View {
    @ObservedObject var state: KeyboardState
    @State private var peek: ClipPeek?

    var body: some View {
        Group {
            if let peek {
                HStack(spacing: 8) {
                    Button {
                        if state.paste(peek), state.panel == .clipboard { state.toggle(.clipboard) }
                    } label: {
                        HStack(spacing: 10) {
                            thumb(peek)
                            VStack(alignment: .leading, spacing: 1) {
                                Text(peek.insertable ? "Aktuell kopiert · Tippen zum Einfügen" : "Aktuell kopiert")
                                    .font(.system(size: 10, weight: .semibold)).foregroundStyle(.secondary)
                                Text(peek.preview).font(.footnote.weight(.semibold)).lineLimit(2)
                            }
                            Spacer(minLength: 0)
                        }
                        .contentShape(Rectangle())
                    }
                    .buttonStyle(PressableStyle())
                    if peek.kind == .image {
                        Button { state.peekToSticker() } label: {
                            Label("Sticker", systemImage: "face.smiling.inverse")
                                .font(.caption.weight(.semibold))
                                .padding(.horizontal, 10).frame(height: 30)
                                .glassCapsule(tint: state.tint.opacity(0.3), interactive: true)
                        }
                        .buttonStyle(.plain)
                    }
                }
                .padding(8)
                .frame(maxWidth: .infinity, alignment: .leading)
                .background(RoundedRectangle(cornerRadius: 14, style: .continuous).fill(state.tint.opacity(0.16)))
                .overlay(RoundedRectangle(cornerRadius: 14, style: .continuous).strokeBorder(state.tint.opacity(0.3), lineWidth: 0.5))
                .transition(.opacity)
            }
        }
        .onAppear(perform: load)
    }

    private func load() {
        peek = state.currentClipPeek { img in
            peek?.thumbnail = img
        }
    }

    @ViewBuilder
    private func thumb(_ p: ClipPeek) -> some View {
        if let img = p.thumbnail {
            Image(uiImage: img).resizable().scaledToFill()
                .frame(width: 40, height: 40)
                .clipShape(RoundedRectangle(cornerRadius: 9, style: .continuous))
        } else {
            Image(systemName: p.icon)
                .font(.system(size: 15, weight: .bold)).foregroundStyle(.white)
                .frame(width: 40, height: 40)
                .background(RoundedRectangle(cornerRadius: 9, style: .continuous).fill(state.tint.gradient))
        }
    }
}
